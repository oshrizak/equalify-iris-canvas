"""Iris HTML through the connector's renderers: Canvas Page, notes, signals,
sanitizer, and the alt formats that cannot read MathML themselves."""

from __future__ import annotations

import time

from connector.canvas.alt_formats import (
    has_math_content,
    html_full_document,
    html_to_plain_text,
)
from connector.canvas.braille import build_blocks
from connector.canvas.iris_notes import format_pages, notes_for_job
from connector.canvas.markdown_to_html import RenderedPage, render_html_body
from connector.canvas.sanitize import sanitize_html
from connector.canvas.signals import derive_signals_from_html
from connector.canvas.state import CanvasJob

MATH_BODY = (
    "<h1>Kinematics</h1>"
    '<hr role="doc-pagebreak" aria-label="Page 214" id="page-214">'
    '<p>Distance is <math alttext="v t"><mi>v</mi><mi>t</mi></math>.</p>'
    '<math display="block" alttext="x_i^2"><msubsup><mi>x</mi><mi>i</mi><mn>2</mn></msubsup></math>'
)


def test_canvas_page_body_has_banner_link_and_no_scope_rewrites():
    body = (
        '<table><tr><th scope="col">A</th><th scope="col">B</th></tr>'
        "<tr><td>1</td><td>2</td></tr></table>"
    )
    page = render_html_body(body, title="Doc", original_pdf_url="/courses/1/files/2")
    assert "generated by Equalify Iris" in page.html
    assert '<a href="/courses/1/files/2">Original PDF</a>' in page.html
    # A header row Iris wrote keeps its column scopes.
    assert 'scope="row"' not in page.html


def test_non_english_documents_are_wrapped_in_their_language():
    page = render_html_body("<p>Hola</p>", title="Doc", lang="es")
    assert '<div lang="es">' in page.html
    assert page.lang == "es"
    english = render_html_body("<p>Hi</p>", title="Doc", lang="en-US")
    assert "<div lang" not in english.html


def test_bad_language_tags_fall_back_to_english():
    page = render_html_body("<p>x</p>", title="Doc", lang='en"><script>')
    assert page.lang == "en" and "<script>" not in page.html


def test_ip_literals_are_defused_for_the_canvas_waf():
    page = render_html_body('<p><a href="http://128.4.1.9/tool">SPRITE</a></p>', title="Doc")
    assert "128&#46;4&#46;1&#46;9" in page.html


def test_sanitizer_keeps_iris_markup():
    clean = sanitize_html(
        MATH_BODY
        + '<p><a href="tel:+15105551212">Call</a> <a href="javascript:alert(1)">x</a></p>'
        + '<span class="iris-image-description">Image: a map</span>'
    )
    assert "<msubsup>" in clean and 'alttext="x_i^2"' in clean
    assert 'role="doc-pagebreak"' in clean and 'aria-label="Page 214"' in clean
    assert 'href="tel:+15105551212"' in clean
    assert "javascript:" not in clean
    assert 'class="iris-image-description"' in clean


def test_plain_text_reads_maths_as_latex():
    text = html_to_plain_text(RenderedPage(title="t", html=MATH_BODY))
    assert "\\(v t\\)" in text and "\\[x_i^2\\]" in text
    assert "v t ." not in text  # not the bare MathML tokens


def test_mathml_counts_as_math_content():
    assert has_math_content(RenderedPage(title="t", html=MATH_BODY))
    assert not has_math_content(RenderedPage(title="t", html="<p>No math, $5 and $7.</p>"))


def test_full_document_declares_the_document_language():
    doc = html_full_document(RenderedPage(title="t", html="<p>Hola</p>", lang="es"), mathjax=False)
    assert '<html lang="es">' in doc


def test_braille_sees_print_pages_and_maths_runs():
    blocks = build_blocks(RenderedPage(title="Kinematics", html=MATH_BODY))
    kinds = [b.kind for b in blocks]
    assert "page_number" in kinds
    assert any(b.page_label == "214" for b in blocks if b.kind == "page_number")
    math_runs = [r.text for b in blocks for r in b.runs if r.is_math]
    assert "v t" in math_runs and "x_i^2" in math_runs


def test_signals_from_iris_html():
    body = (
        "<h1>T</h1><h2>S</h2>"
        '<img src="a" alt="Bar chart of enrolment"><img src="b" alt=""><img src="c" alt="image">'
        "<table><tr><th>x</th></tr></table><table><tr><td>y</td></tr></table>"
    )
    s = derive_signals_from_html(body, lang="en", has_text_layer=False, report={"failed_pages": [2]})
    assert s["heading_levels"] == [1, 2]
    assert s["images_total"] == 2  # decorative image is a decision, not a gap
    assert s["images_with_alt"] == 1  # "image" is a placeholder, not a description
    assert (s["tables_total"], s["tables_semantic"]) == (2, 1)
    assert s["has_text_layer"] is False and s["_pdf_classification"] == "scanned"
    assert s["_iris_failed_pages"] == [2]


def _iris_job(**kw) -> CanvasJob:
    base = dict(
        reflow_job_id="j1", canvas_file_id="f1", canvas_file_name="Reading.pdf",
        canvas_course_id="c1", canvas_user_id="u1", status="awaiting_review",
        created_at=time.time(), backend="iris", completed_at=time.time(),
    )
    base.update(kw)
    return CanvasJob(**base)


def test_format_pages():
    assert format_pages([3, 4, 5, 9]) == "3-5 and 9"
    assert format_pages([7]) == "7"
    assert format_pages([1, 3, 4, 8]) == "1, 3-4 and 8"


def test_notes_put_missing_content_first():
    job = _iris_job(
        iris_report={
            "failed_pages": [12], "uncorrected_pages": [5, 31],
            "unresolved": ["Heading levels skip on page 2"], "parts": 2,
        },
        iris_parts=[
            {"index": 0, "first_page": 1, "last_page": 25},
            {"index": 1, "first_page": 26, "last_page": 50},
        ],
        source_page_count=50,
        iris_figures=[{"ref": "figures/p4-1.png", "page": 4, "index_on_page": 1, "alt": "Map"}],
        iris_figures_unmatched=["figures/p4-1.png"],
    )
    notes = notes_for_job(job)
    codes = [n["code"] for n in notes]
    assert codes == [
        "pages_missing", "pages_unverified", "open_issues", "figures_as_text", "converted_in_parts",
    ]
    assert "page 12" in notes[0]["message"]
    assert "Pages 5 and 31" in notes[1]["message"]
    assert notes[2]["items"] == ["Heading levels skip on page 2"]
    assert "pages 25-26" in notes[-1]["message"] and "50-page" in notes[-1]["message"]


def test_no_notes_for_a_clean_job_or_a_reflow_job():
    assert notes_for_job(_iris_job(iris_report={"parts": 1})) == []
    legacy = _iris_job(backend="reflow", iris_report={"failed_pages": [1]})
    assert notes_for_job(legacy) == []
